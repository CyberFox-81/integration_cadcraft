# Build CADCraft for the browser, with the embedding bridge from patches/, into web/.
#
# Usage: scripts/build-cadcraft-web.sh [CADCRAFT_CHECKOUT]
#
#   CADCRAFT_CHECKOUT  an existing clone of github.com/storytold/cadcraft. Without it the
#                       script clones CADCRAFT_REF into build/cadcraft.
#
# Needs: Rust with the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown)
# and wasm-bindgen-cli at the version in CADCraft's Cargo.lock
# (cargo install wasm-bindgen-cli --version <x.y.z> --locked). wasm-opt (binaryen) is used
# when installed and shrinks the download.
#
# Environment:
#   CADCRAFT_REF  commit or tag to clone (default: the commit the patch was made against)
#   BUILD_STD=1    build the standard library from source (when the wasm32 target can't be
#                  installed through rustup but rust-src is available)
#   FAST=1         skip LTO and use parallel codegen: quicker builds, bigger wasm
#   CRAFT_FONTS_DIR  a clone of storytold/craft-fonts, to embed the shared Japanese fonts
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CADCRAFT_REF="${CADCRAFT_REF:-fc4220e9b7d7cc8e9d26704ccf0078d94caaa6c0}"
SRC="${1:-$APP_DIR/build/cadcraft}"
PATCH="$APP_DIR/patches/cadcraft-nextcloud.patch"
OUT="$APP_DIR/web"
TARGET_DIR="${CARGO_TARGET_DIR:-$SRC/target}"

if [ ! -e "$SRC/.git" ]; then
	git clone https://github.com/storytold/cadcraft.git "$SRC"
	git -C "$SRC" checkout --quiet "$CADCRAFT_REF"
fi

if grep -rq 'cadcraft:ready' "$SRC/apps/cadcraft-web/src"; then
	echo "bridge patch already applied"
else
	git -C "$SRC" apply "$PATCH"
fi

cargo_args=(build --profile release -p cadcraft-web --target wasm32-unknown-unknown)
if [ "${BUILD_STD:-0}" = "1" ]; then
	export RUSTC_BOOTSTRAP=1
	cargo_args+=(-Zbuild-std=std,panic_abort)
fi
if [ "${FAST:-0}" = "1" ]; then
	export CARGO_PROFILE_RELEASE_LTO=off CARGO_PROFILE_RELEASE_CODEGEN_UNITS=16
fi
(cd "$SRC" && CARGO_TARGET_DIR="$TARGET_DIR" cargo "${cargo_args[@]}")

WASM_IN="$TARGET_DIR/wasm32-unknown-unknown/release/cadcraft-web.wasm"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
wasm-bindgen --target web --weak-refs --no-typescript --out-dir "$STAGE" --out-name cadcraft-web "$WASM_IN"

if command -v wasm-opt >/dev/null; then
	wasm-opt -Oz --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
		--enable-mutable-globals --enable-reference-types --enable-multivalue \
		"$STAGE/cadcraft-web_bg.wasm" -o "$STAGE/cadcraft-web_bg.opt.wasm"
	mv "$STAGE/cadcraft-web_bg.opt.wasm" "$STAGE/cadcraft-web_bg.wasm"
else
	echo "note: wasm-opt not found; the wasm is not size-optimized"
fi

# Content-hashed names: Nextcloud lets browsers cache app assets for months.
hash() { sha256sum "$1" | cut -c1-16; }
JS_NAME="cadcraft-web-$(hash "$STAGE/cadcraft-web.js").js"
WASM_NAME="cadcraft-web-$(hash "$STAGE/cadcraft-web_bg.wasm").wasm"

mkdir -p "$OUT"
rm -f "$OUT"/cadcraft-web-*.js "$OUT"/cadcraft-web-*.wasm
cp "$STAGE/cadcraft-web.js" "$OUT/$JS_NAME"
cp "$STAGE/cadcraft-web_bg.wasm" "$OUT/$WASM_NAME"
# JavaScript the Rust code brings along (`#[wasm_bindgen(module = …)]`), imported by the glue.
rm -rf "$OUT/snippets"
if [ -d "$STAGE/snippets" ]; then cp -R "$STAGE/snippets" "$OUT/snippets"; fi

# CADCraft's licenses and the attributions for the fonts and assets compiled into it.
for f in LICENSE-MIT LICENSE-APACHE NOTICE ATTRIBUTION.md ASSETS.md; do
	if [ -f "$SRC/$f" ]; then cp "$SRC/$f" "$OUT/CADCRAFT-$f"; fi
done

cat > "$OUT/boot.js" <<BOOT
/*
 * SPDX-FileCopyrightText: 2026 Britton Couchman <brittondcouchman@gmail.com>
 * SPDX-License-Identifier: AGPL-3.0-or-later
 *
 * Starts CADCraft in the editor's iframe (templates/frame.php).
 * Generated by scripts/build-cadcraft-web.sh from CADCraft $(git -C "$SRC" rev-parse --short HEAD).
 */

function reportFailure(error) {
	console.error('CADCraft could not start', error)
	if (window.parent !== window) {
		window.parent.postMessage({ type: 'cadcraft:failed', error: String(error?.message ?? error) }, window.location.origin)
	}
}

try {
	const app = await import('./$JS_NAME')
	await app.default({ module_or_path: new URL('./$WASM_NAME', import.meta.url) })

} catch (error) {
	reportFailure(error)
}
BOOT

echo "CADCraft web build:"
ls -lh "$OUT"
